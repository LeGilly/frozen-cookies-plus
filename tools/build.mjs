#!/usr/bin/env node
// Builds the self-contained Steam mod:
//   Steam/FrozenCookiesPlus/info.txt
//   Steam/FrozenCookiesPlus/main.js      (all libraries + scripts inlined)
//   dist/FrozenCookiesPlus-<version>.zip  (if the `zip` command exists)
// Usage: npm run build (or node tools/build.mjs)

import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const loader = fs.readFileSync(path.join(root, "frozen_cookies.js"), "utf8");

function listFrom(name) {
    const m = loader.match(new RegExp("var " + name + " = \\[([\\s\\S]*?)\\];"));
    if (!m) throw new Error("could not find " + name + " in frozen_cookies.js");
    return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const version = loader.match(/version: "([^"]+)"/)[1];
const gameVersion = loader.match(/var steamGameVersion = ([0-9.]+)/)[1];
const files = ["vendor/jquery.min.js", ...listFrom("fcVendorList"), ...listFrom("fcScriptList")];

const bundle = files.map((f) => [f, fs.readFileSync(path.join(root, f), "utf8")]);

const header =
    "// Frozen Cookies Plus " + version + " — Steam bundle, generated by tools/build.mjs. Do not edit.\n" +
    "// Source and licenses: see README.md (GPL-3.0-or-later; bundled libraries keep their own licenses).\n";
const main = header + "window.FCP_BUNDLE = { files: " + JSON.stringify(bundle) + " };\n" + loader;

const outDir = path.join(root, "Steam", "FrozenCookiesPlus");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "main.js"), main);

const today = new Date();
const pad = (n) => String(n).padStart(2, "0");
const info = {
    Name: "Frozen Cookies Plus",
    ID: "frozen_cookies_plus",
    Author: "Legilly (based on Frozen Cookies by Icehawk78 and erbkaiser)",
    Description:
        "Frozen Cookies, updated for Cookie Clicker " + gameVersion + " (Steam), plus achievement hunting, sugar lump levelling, a garden seed breeder and stock trading.",
    ModVersion: version,
    GameVersion: Number(gameVersion),
    Date: today.getFullYear() + "/" + pad(today.getMonth() + 1) + "/" + pad(today.getDate()),
    Dependencies: [],
    Disabled: 0,
    AllowSteamAchievs: 1,
};
fs.writeFileSync(path.join(outDir, "info.txt"), JSON.stringify(info, null, "\t"));

console.log("Built " + path.relative(root, outDir) + " (" + (main.length / 1024).toFixed(0) + " KB, " + files.length + " files inlined)");

try {
    const dist = path.join(root, "dist");
    fs.mkdirSync(dist, { recursive: true });
    const zip = path.join(dist, "FrozenCookiesPlus-" + version + ".zip");
    if (fs.existsSync(zip)) fs.unlinkSync(zip);
    execSync('zip -qr "' + zip + '" FrozenCookiesPlus', { cwd: path.join(root, "Steam") });
    console.log("Zipped " + path.relative(root, zip));
} catch (e) {
    console.log("(zip skipped: " + e.message.split("\n")[0] + ")");
}
